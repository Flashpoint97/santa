"""SQLAlchemy 2 declarative models: the single source of truth for the schema.

Alembic migrations are autogenerated from this file. Every relationship is FK-backed with
ON DELETE CASCADE plus an ORM cascade, so deleting an event removes everything under it
in one transaction. The one exception is the Partner link, a nullable self-FK that is
SET NULL rather than cascaded: removing a Participant must not remove their Partner.

Nothing here is personal data; the rows are filled at runtime by the organizer's CLI.
"""

import uuid
from datetime import UTC, datetime
from decimal import Decimal

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    Dialect,
    ForeignKey,
    Index,
    Integer,
    LargeBinary,
    MetaData,
    Numeric,
    String,
    Text,
    TypeDecorator,
    UniqueConstraint,
    Uuid,
    func,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


class UTCDateTime(TypeDecorator[datetime]):
    """Timezone-aware UTC datetimes on every backend.

    Postgres stores `timestamptz`; SQLite (used by the fast local test run) has no timezone
    support, so values are stored as naive UTC there and re-tagged as UTC on the way out.
    """

    impl = DateTime(timezone=True)
    cache_ok = True

    def process_bind_param(self, value: datetime | None, dialect: Dialect) -> datetime | None:
        if value is None:
            return None
        if value.tzinfo is None:
            raise ValueError("naive datetime passed to UTCDateTime")
        value = value.astimezone(UTC)
        return value.replace(tzinfo=None) if dialect.name == "sqlite" else value

    def process_result_value(self, value: datetime | None, dialect: Dialect) -> datetime | None:
        if value is None:
            return None
        return value.replace(tzinfo=UTC) if value.tzinfo is None else value.astimezone(UTC)


def utcnow() -> datetime:
    return datetime.now(UTC)


class Base(DeclarativeBase):
    # Deterministic constraint names so migrations are reviewable and portable.
    metadata = MetaData(
        naming_convention={
            "ix": "ix_%(column_0_label)s",
            "uq": "uq_%(table_name)s_%(column_0_name)s",
            "ck": "ck_%(table_name)s_%(constraint_name)s",
            "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
            "pk": "pk_%(table_name)s",
        }
    )


class Event(Base):
    """The one gift exchange of this deployment (the loader refuses to create a second)."""

    __tablename__ = "events"

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    name: Mapped[str] = mapped_column(String(200), nullable=False)
    budget_amount: Mapped[Decimal] = mapped_column(Numeric(10, 2), nullable=False)
    budget_currency: Mapped[str] = mapped_column(String(3), nullable=False, default="EUR")
    # The instant of the exchange. The list file gives Europe/Zagreb local time; it is
    # converted before it reaches this column.
    exchange_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False)
    place: Mapped[str] = mapped_column(String(300), nullable=False)
    after_event_message: Mapped[str] = mapped_column(Text, nullable=False)
    drawn_at: Mapped[datetime | None] = mapped_column(UTCDateTime)
    created_at: Mapped[datetime] = mapped_column(
        UTCDateTime, nullable=False, default=utcnow, server_default=func.now()
    )

    participants: Mapped[list["Participant"]] = relationship(
        back_populates="event", cascade="all, delete-orphan", passive_deletes=True
    )
    assignments: Mapped[list["Assignment"]] = relationship(
        back_populates="event", cascade="all, delete-orphan", passive_deletes=True
    )


class Participant(Base):
    __tablename__ = "participants"
    __table_args__ = (
        UniqueConstraint("event_id", "display_name", name="uq_participants_event_display_name"),
        CheckConstraint("partner_id IS NULL OR partner_id <> id", name="partner_not_self"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    # The access-scoping column: NOT NULL, so a participant always belongs to exactly one event.
    event_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("events.id", ondelete="CASCADE"), nullable=False, index=True
    )
    display_name: Mapped[str] = mapped_column(String(100), nullable=False)
    # Croatian case forms are supplied by the organizer instead of declined automatically.
    vocative_name: Mapped[str] = mapped_column(String(100), nullable=False)  # greetings
    accusative_name: Mapped[str] = mapped_column(String(100), nullable=False)  # "you give to ..."
    # Partners never draw each other. The loader keeps the link symmetric; the database only
    # guarantees it is not a self-reference. SET NULL (not CASCADE) so deleting one person
    # never deletes their Partner.
    partner_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("participants.id", ondelete="SET NULL"), index=True
    )
    note: Mapped[str] = mapped_column(Text, nullable=False, default="")
    # HMAC of the 6-digit code (keyed, so it can be looked up but not brute-forced from a
    # dump). Unique: the code alone identifies the person at login.
    code_hash: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)
    has_logged_in: Mapped[bool] = mapped_column(nullable=False, default=False)
    # NULL until the first reveal. Setting it atomically decides who sees the "first time" text.
    first_revealed_at: Mapped[datetime | None] = mapped_column(UTCDateTime)
    created_at: Mapped[datetime] = mapped_column(
        UTCDateTime, nullable=False, default=utcnow, server_default=func.now()
    )

    event: Mapped[Event] = relationship(back_populates="participants")
    sessions: Mapped[list["Session"]] = relationship(
        back_populates="participant", cascade="all, delete-orphan", passive_deletes=True
    )
    # The clip of the person this participant *shows* (not the one they drew).
    animation: Mapped["Animation | None"] = relationship(
        back_populates="participant",
        uselist=False,
        cascade="all, delete-orphan",
        passive_deletes=True,
    )
    given_assignment: Mapped["Assignment | None"] = relationship(
        back_populates="giver",
        foreign_keys="Assignment.giver_id",
        uselist=False,
        cascade="all, delete-orphan",
        passive_deletes=True,
    )
    received_assignment: Mapped["Assignment | None"] = relationship(
        back_populates="receiver",
        foreign_keys="Assignment.receiver_id",
        uselist=False,
        cascade="all, delete-orphan",
        passive_deletes=True,
    )


class Assignment(Base):
    """Who buys for whom. The unique constraints make the draw a permutation at the DB level."""

    __tablename__ = "assignments"
    __table_args__ = (CheckConstraint("giver_id <> receiver_id", name="not_self"),)

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    event_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("events.id", ondelete="CASCADE"), nullable=False, index=True
    )
    giver_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("participants.id", ondelete="CASCADE"), nullable=False, unique=True
    )
    receiver_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("participants.id", ondelete="CASCADE"), nullable=False, unique=True
    )

    event: Mapped[Event] = relationship(back_populates="assignments")
    giver: Mapped[Participant] = relationship(
        back_populates="given_assignment", foreign_keys=[giver_id]
    )
    receiver: Mapped[Participant] = relationship(
        back_populates="received_assignment", foreign_keys=[receiver_id]
    )


class Animation(Base):
    """The looping clip of one Participant (the person *shown*), stored as bytes in the DB.

    Eight short clips fit easily in Neon's free tier and keep the whole app on one datastore.
    """

    __tablename__ = "animations"
    __table_args__ = (CheckConstraint("byte_size > 0", name="not_empty"),)

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    participant_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("participants.id", ondelete="CASCADE"), nullable=False, unique=True
    )
    video: Mapped[bytes] = mapped_column(LargeBinary, nullable=False)
    content_type: Mapped[str] = mapped_column(String(100), nullable=False)
    byte_size: Mapped[int] = mapped_column(Integer, nullable=False)

    participant: Mapped[Participant] = relationship(back_populates="animation")


class Session(Base):
    """A login session. Only a hash of the bearer token is stored."""

    __tablename__ = "sessions"

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    participant_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("participants.id", ondelete="CASCADE"), nullable=False, index=True
    )
    token_hash: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)
    created_at: Mapped[datetime] = mapped_column(
        UTCDateTime, nullable=False, default=utcnow, server_default=func.now()
    )
    # Inactivity, not age, ends a session: every authenticated request bumps this.
    last_activity_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)

    participant: Mapped[Participant] = relationship(back_populates="sessions")


class RateLimitHit(Base):
    """Sliding-window rate-limit log, kept in Postgres so no Redis is needed.

    `key_hash` is an HMAC of e.g. "login-failure:ip:<addr>" so that raw client IPs are never
    stored.
    """

    __tablename__ = "rate_limit_hits"
    __table_args__ = (Index("ix_rate_limit_key_created", "key_hash", "created_at"),)

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    key_hash: Mapped[str] = mapped_column(String(64), nullable=False)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, nullable=False, default=utcnow)
